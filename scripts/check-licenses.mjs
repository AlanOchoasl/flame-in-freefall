#!/usr/bin/env node
// Checks the license of every package in node_modules against scripts/license-policy.json.
// Usage: node scripts/check-licenses.mjs [projectDir] [--write]
//   --write  also writes THIRD_PARTY_LICENSES.md (required in the submission documentation).
// Exit code 1 if any package is not allowed. Reads local files only; no network.
import { readdirSync, readFileSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const write = args.includes('--write');
const projectDir = args.find((a) => !a.startsWith('--')) ?? process.cwd();
const policyPath = join(dirname(fileURLToPath(import.meta.url)), 'license-policy.json');
const policy = JSON.parse(readFileSync(policyPath, 'utf8'));
const allowed = new Set(policy.allowedLicenses);
const exceptions = new Set(policy.approvedExceptions.map((e) => e.name));

function listPackageDirs(nodeModules) {
  const dirs = [];
  if (!existsSync(nodeModules)) return dirs;
  for (const entry of readdirSync(nodeModules)) {
    if (entry.startsWith('.')) continue;
    const full = join(nodeModules, entry);
    if (!statSync(full).isDirectory()) continue;
    const children = entry.startsWith('@') ? readdirSync(full).map((c) => join(full, c)) : [full];
    for (const pkgDir of children) {
      dirs.push(pkgDir, ...listPackageDirs(join(pkgDir, 'node_modules')));
    }
  }
  return dirs;
}

function readLicense(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

// "MIT", "(MIT OR Apache-2.0)", "MIT AND BSD-3-Clause". Nested parentheses go to manual review.
function isAllowed(expression) {
  const inner = expression.trim().replace(/^\((.*)\)$/, '$1');
  if (inner.includes('(')) return false;
  return inner.split(/\s+OR\s+/).some((alt) => alt.split(/\s+AND\s+/).every((id) => allowed.has(id.trim())));
}

const packages = new Map();
for (const dir of listPackageDirs(join(projectDir, 'node_modules'))) {
  const manifest = join(dir, 'package.json');
  if (!existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
  if (!pkg.name) continue;
  packages.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license: readLicense(pkg) });
}

const rows = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const rejected = rows.filter((p) => !isAllowed(p.license) && !exceptions.has(p.name));

console.log(`Checked ${rows.length} packages.`);
if (rejected.length > 0) {
  console.error('\nNot allowed by license policy (needs team approval or removal):');
  for (const p of rejected) console.error(`  ${p.name}@${p.version}  ->  ${p.license}`);
  console.error('\nTo approve one on purpose, add it to approvedExceptions in scripts/license-policy.json with a reason.');
}

if (write) {
  const lines = ['# Third-party licenses', '', 'Generated by `scripts/check-licenses.mjs --write`.', '', '| Package | Version | License |', '|---|---|---|'];
  for (const p of rows) lines.push(`| ${p.name} | ${p.version} | ${p.license} |`);
  writeFileSync(join(projectDir, 'THIRD_PARTY_LICENSES.md'), lines.join('\n') + '\n');
  console.log('Wrote THIRD_PARTY_LICENSES.md');
}

process.exit(rejected.length > 0 ? 1 : 0);
